// Helper function to get subjects for multiple classes (removes duplicates)
export function getSubjectsForClasses(classes: string[]): Array<{ id: string; name: string; dataType: string }> {
  const subjectsMap = new Map<string, { id: string; name: string; dataType: string }>();
  
  classes.forEach(cls => {
    const subjects = subjectsByClass[cls] || [];
    subjects.forEach(subject => {
      // Use subject name as key to avoid duplicates
      if (!subjectsMap.has(subject.name)) {
        subjectsMap.set(subject.name, subject);
      }
    });
  });
  
  return Array.from(subjectsMap.values());
}

// Helper function to get all unique subject names
export function getAllSubjectNames(): string[] {
  const allSubjects = new Set<string>();
  Object.values(subjectsByClass).forEach(subjects => {
    subjects.forEach(subject => allSubjects.add(subject.name));
  });
  return Array.from(allSubjects);
} 

export function getSubjectById(classAssigned: string, subjectId: string): { id: string; name: string; dataType: string } | null {
  const subjects = subjectsByClass[classAssigned];
  if (!subjects) return null;
  return subjects.find(subj => subj.id === subjectId) || null;
}

// Helper function to get subjects for a single class
export function getSubjectsForClass(classValue: string): Array<{ id: string; name: string; dataType: string }> {
  return subjectsByClass[classValue] || [];
}

export function getSubjectsByPrefixes(
  classValue: string,
  prefixes: string[]
): Array<{ id: string; name: string; dataType: string }> {
  const subjects = subjectsByClass[classValue] || [];
  if (prefixes.length === 0) return [];
  return subjects.filter((subject) =>
    prefixes.some((prefix) => subject.id.startsWith(prefix))
  );
}

type SubjectChoiceFields = {
  secondLanguageSubject?: string | null;
  thirdLanguageSubject?: string | null;
  sixthSubject?: string | null;
  valueFaithSubject?: string | null;
};

const getPreferredSubjectId = (
  classValue: string,
  prefix: string,
  preferredId: string,
  choice?: string | null
): string | null => {
  const candidates = getSubjectsByPrefixes(classValue, [prefix]);
  if (candidates.length === 0) return null;
  if (choice && candidates.some((candidate) => candidate.id === choice)) {
    return choice;
  }
  const preferred = candidates.find((candidate) => candidate.id === preferredId);
  return preferred?.id || candidates[0].id;
};

const getPreferredSubjectIdForPrefixes = (
  classValue: string,
  prefixes: string[],
  preferredId: string,
  choice?: string | null
): string | null => {
  const candidates = getSubjectsByPrefixes(classValue, prefixes);
  if (candidates.length === 0) return null;
  if (choice && candidates.some((candidate) => candidate.id === choice)) {
    return choice;
  }
  const preferred = candidates.find((candidate) => candidate.id === preferredId);
  return preferred?.id || candidates[0].id;
};

export function getSubjectChoiceDefaults(
  classValue: string,
  choices?: SubjectChoiceFields
): Required<SubjectChoiceFields> {
  const secondLanguageSubject = getPreferredSubjectId(
    classValue,
    '2ND-LANG-',
    `2ND-LANG-HIN-${classValue}`,
    choices?.secondLanguageSubject
  );
  const thirdLanguageSubject = getPreferredSubjectId(
    classValue,
    '3RD-LANG-',
    `3RD-LANG-HIN-${classValue}`,
    choices?.thirdLanguageSubject
  );
  const sixthSubject = getPreferredSubjectId(
    classValue,
    '6TH-SUB-',
    `6TH-SUB-COMP-${classValue}`,
    choices?.sixthSubject
  );
  const valueFaithSubject = getPreferredSubjectIdForPrefixes(
    classValue,
    ['VAL-EDU-', 'FAITH-EDU-'],
    `VAL-EDU-${classValue}`,
    choices?.valueFaithSubject
  );

  return {
    secondLanguageSubject,
    thirdLanguageSubject,
    sixthSubject,
    valueFaithSubject,
  };
}

export function getSubjectsForClassWithChoices(
  classValue: string,
  choices?: SubjectChoiceFields
): Array<{ id: string; name: string; dataType: string }> {
  const subjects = subjectsByClass[classValue] || [];
  if (subjects.length === 0) return [];

  const defaults = getSubjectChoiceDefaults(classValue, choices);

  return subjects.filter((subject) => {
    if (subject.id.startsWith('2ND-LANG-')) {
      return defaults.secondLanguageSubject
        ? subject.id === defaults.secondLanguageSubject
        : true;
    }
    if (subject.id.startsWith('3RD-LANG-')) {
      return defaults.thirdLanguageSubject
        ? subject.id === defaults.thirdLanguageSubject
        : true;
    }
    if (subject.id.startsWith('6TH-SUB-')) {
      return defaults.sixthSubject ? subject.id === defaults.sixthSubject : true;
    }
    if (subject.id.startsWith('VAL-EDU-') || subject.id.startsWith('FAITH-EDU-')) {
      return defaults.valueFaithSubject
        ? subject.id === defaults.valueFaithSubject
        : true;
    }
    return true;
  });
}

export function resolveLegacySubjectCode(
  classValue: string,
  subjectCode: string,
  choices?: SubjectChoiceFields
): string {
  if (!subjectCode || !classValue) return subjectCode;

  const legacy2nd = /^2ND-LANG-\d+$/;
  const legacy3rd = /^3RD-LANG-\d+$/;
  const legacy6th = /^6TH-SUB-\d+$/;
  const defaults = getSubjectChoiceDefaults(classValue, choices);

  if (legacy2nd.test(subjectCode)) {
    return defaults.secondLanguageSubject || subjectCode;
  }

  if (legacy3rd.test(subjectCode)) {
    return defaults.thirdLanguageSubject || subjectCode;
  }

  if (legacy6th.test(subjectCode)) {
    return defaults.sixthSubject || subjectCode;
  }

  return subjectCode;
}

